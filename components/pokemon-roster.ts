/**
 * The twelve creatures, their sprites and their cries.
 *
 * The sprites are from the public-domain "50 monochrome 32 by 32 critters"
 * set on OpenGameArt, released under CC0 1.0 Universal, which waives copyright
 * entirely and asks for no attribution:
 *
 *   https://opengameart.org/content/30-public-domain-monochrome-sprites
 *
 * They were sliced out of the sheet, trimmed to their ink and fitted to the
 * 28x28 grid used here. Being 1-bit black on white they need no recolouring to
 * sit in the four-tone Game Boy palette: "3" is the darkest tone and "." is
 * the background.
 *
 * This replaced a set drawn from a small shape DSL. That kept the file short
 * but every creature came out as the same ellipse with different bumps, which
 * is the one thing a roster of twelve cannot afford.
 */

export const SPRITE_SIZE = 28

/**
 * A cry.
 *
 * Generation I cries were short bursts of noise and pitch sweep, and no two
 * sounded alike. Each species carries its own shape here: where the sweep
 * starts and ends, how long it lasts, how rough it is, and what waveform
 * carries it.
 */
interface Cry {
  from: number
  to: number
  duration: number
  wave: "square" | "sawtooth" | "triangle" | "sine"
  /** How much filtered noise rides on top, 0 to 1. */
  grit: number
}

/**
 * The four types, in a single cycle: CODE beats DATA beats METAL beats CHAOS
 * beats CODE. One ring keeps the chart learnable inside a battle or two while
 * still making the choice of move matter.
 */
export type MonType = "CODE" | "DATA" | "METAL" | "CHAOS"

const BEATS: Record<MonType, MonType> = {
  CODE: "DATA",
  DATA: "METAL",
  METAL: "CHAOS",
  CHAOS: "CODE",
}

/** 2 super effective along the ring, 0.5 against the ring, 1 otherwise. */
export function effectiveness(attack: MonType, defend: MonType): number {
  if (BEATS[attack] === defend) return 2
  if (BEATS[defend] === attack) return 0.5
  return 1
}

export interface Move {
  name: string
  /** Zero for a status move; the effect is the whole point of using it. */
  power: number
  pp: number
  maxPp: number
  type: MonType
  /** Per-use chance to land, out of 100. */
  accuracy: number
  /** Stat-stage moves: lower the foe's attack or defence, or raise your own. */
  effect?: "atkDown" | "defDown" | "defUp"
}

export interface Species {
  name: string
  type: MonType
  level: number
  maxHp: number
  moves: Move[]
  cry: Cry
  /** One string per row of the 28x28 grid: "." is background, "0" to "3" are
   *  the four Game Boy tones from lightest to darkest. */
  sprite: string[]
}

const mv = (
  name: string,
  power: number,
  pp: number,
  type: MonType,
  accuracy: number,
  effect?: Move["effect"],
): Move => ({ name, power, pp, maxPp: pp, type, accuracy, effect })

